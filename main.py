# Преобразуем в DataFrame (таблицу)
df = pd.DataFrame(data)

# 2. Предобработка текста и векторизация
# Создаём объекты для обработки текста
vectorizer = TfidfVectorizer(
    max_features=1000,  # Используем топ-1000 слов
    stop_words='english',  # Удаляем стоп-слова
    lowercase=True  # Приводим к нижнему регистру
)

X = vectorizer.fit_transform(df['texts'])  # Преобразуем текст в векторы
y = df['labels']  # Метки классов

# 3. Разбиение на обучающую и тестовую выборки
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42, stratify=y)

# 4. Создание и обучение модели
model = LogisticRegression()  # Создаем модель
model.fit(X_train, y_train)  # Обучаем на тренировочных данных

# 5. Оценка модели
# Предсказание на тестовых данных
y_pred = model.predict(X_test)

# Вычисляем точность
accuracy = accuracy_score(y_test, y_pred)
print(f"Точность модели: {accuracy:.2f}")  # Выводим точность

# 6. Подробный отчет по классификации
print("\nПодробный отчет:")
print(classification_report(y_test, y_pred))

# 7. Пример использования обученной модели
def predict_sentiment(text):
    # Преобразуем новый текст в вектор
    text_vector = vectorizer.transform([text])
    # Предсказываем класс
    prediction = model.predict(text_vector)
    # Возвращаем результат
    sentiment = "Позитивный" if prediction[0] == 1 else "Негативный"
    return f"Текст: '{text}'\nТональность: {sentiment}"

# Пример использования функции
sample_text = "Это был ужасный день!"
print("\nПример использования:")
print(predict_sentiment(sample_text))

